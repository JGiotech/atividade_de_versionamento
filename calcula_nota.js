// Função para média de notas
function calcularMedia(nota1, nota2) {
    return (nota1 + nota2) / 2;
}

// Calcula a média
let media = calcularMedia(8, 7);

// Imprime resultado
console.log("A média do aluno é:", media, "- Alteração da Giovanna, eu mesma.");
